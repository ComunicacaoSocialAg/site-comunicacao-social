// Carrega os posts do localStorage (quando no navegador) combinados com os nativos
export function getStoredPosts() {
  if (typeof window === 'undefined') {
    return BUILTIN_MARKET_POSTS;
  }
  try {
    const raw = window.localStorage.getItem('csag_market_posts_custom');
    if (!raw) return BUILTIN_MARKET_POSTS;
    const custom = JSON.parse(raw);
    if (!Array.isArray(custom)) return BUILTIN_MARKET_POSTS;

    // Combina: os customizados têm prioridade por ID/slug ou são adicionados no topo
    const customIds = new Set(custom.map((p) => p.slug || p.id));
    const merged = [
      ...custom,
      ...BUILTIN_MARKET_POSTS.filter((p) => !customIds.has(p.slug || p.id)),
    ];
    return merged;
  } catch (err) {
    console.warn('Erro ao carregar posts locais:', err);
    return BUILTIN_MARKET_POSTS;
  }
}

// Salva a lista de posts no localStorage
export function saveCustomPosts(posts) {
  if (typeof window === 'undefined') return false;
  try {
    window.localStorage.setItem('csag_market_posts_custom', JSON.stringify(posts));
    return true;
  } catch (err) {
    console.error('Falha ao salvar posts customizados:', err);
    return false;
  }
}
